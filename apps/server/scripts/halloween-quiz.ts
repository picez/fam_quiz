type Cell = ReturnType<typeof cell>;

/** Детермінований генератор (mulberry32) із зерном із рядка. */
const random = (seed: string) => {
  let a = [...seed].reduce((h, ch) => Math.imul(h ^ ch.charCodeAt(0), 16777619), 2166136261) >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let x = Math.imul(a ^ (a >>> 15), 1 | a);
    x = (x + Math.imul(x ^ (x >>> 7), 61 | x)) ^ x;
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
};

/**
 * Множник (×2 чи ×3 навмання) і бліц-клітинка — на випадкових цінах, щоб гравці не мали шаблону.
 * Бліц-клітинка є приблизно в половині категорій і не потрапляє на клітинку вголос.
 */
const scatter = (seed: string, cells: Cell[]): Cell[] => {
  const next = random(`halloween-${seed}`);
  const out: Cell[] = [...cells].sort((x, y) => x.question.points - y.question.points).map((c) => ({ ...c, mark: 'none', kind: 'normal', penalty: 'none' }));
  const marked = Math.floor(next() * out.length);
  out[marked] = { ...out[marked], mark: next() < 0.5 ? 'x2' : 'x3' };
  if (next() < 0.55) {
    const simple: readonly string[] = ['single', 'boolean', 'numeric', 'text'];
    const free = out.map((_, i) => i).filter((i) => i !== marked && out[i].answerMode !== 'voice' && simple.includes(out[i].question.type));
    if (free.length > 0) {
      const b = free[Math.floor(next() * free.length)];
      out[b] = { ...out[b], kind: 'blitz' };
    }
  }
  return out;
};

