/** Перемішує запитання так, щоб теми не йшли поспіль: ставить наступним перше, тема якого відрізняється від попередньої. */
const spread = (qs: Question[]): Question[] => {
  const left = [...qs];
  const out: Question[] = [];
  while (left.length) {
    const prev = out.at(-1)?.id.split('-')[0];
    const i = left.findIndex((q) => q.id.split('-')[0] !== prev);
    out.push(...left.splice(i < 0 ? 0 : i, 1));
  }
  return out;
};

