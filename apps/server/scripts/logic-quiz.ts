/** Тема запитання за його id. */
export const logicThemeOf = (id: string): LogicTheme | null => {
  const code = id.split('-')[0];
  return code in LOGIC_THEMES ? (code as LogicTheme) : null;
};

/** Детермінований генератор (mulberry32) із зерном із рядка — як у «Касеті й DVD». */
const random = (seed: string) => {
  let a = [...seed].reduce((h, ch) => Math.imul(h ^ ch.charCodeAt(0), 16777619), 2166136261) >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let x = Math.imul(a ^ (a >>> 15), 1 | a);
    x = (x + Math.imul(x ^ (x >>> 7), 61 | x)) ^ x;
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
};

/**
 * ×2 або ×3 і бліц-клітинка на випадкових цінах (зерно — ключ категорії), без шаблону. У кожній категорії один множник,
 * приблизно в половині категорій ще й бліц-клітинка на іншій ціні (не на клітинці вголос).
 */
const scatter = (key: string, cells: Cell[]): Cell[] => {
  const next = random(`logic-${key}`);
  const out: Cell[] = cells.map((c) => ({ ...c, mark: 'none', kind: 'normal', penalty: 'none' }));
  const marked = Math.floor(next() * out.length);
  out[marked] = { ...out[marked], mark: next() < 0.5 ? 'x2' : 'x3' };
  if (next() < 0.5) {
    const free = out.map((_, i) => i).filter((i) => i !== marked && out[i].answerMode !== 'voice');
    if (free.length) {
      const b = free[Math.floor(next() * free.length)];
      out[b] = { ...out[b], kind: 'blitz' };
    }
  }
  return out;
};

