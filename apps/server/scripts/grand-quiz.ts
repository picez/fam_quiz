export type GrandTheme = keyof typeof GRAND_THEMES;

/** Тема запитання за його id; null — опитування чи «хмара». */
export const grandThemeOf = (id: string): GrandTheme | null => {
  const code = id.split('-')[0];
  return code in GRAND_THEMES ? (code as GrandTheme) : null;
};

