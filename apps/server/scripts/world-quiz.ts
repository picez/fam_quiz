/** Десять тем вечора; код теми — префікс id кожного запитання (зручно для статистики за темами). */
export const WORLD_THEMES = {
  geo: 'Географія',
  flora: 'Флора',
  fauna: 'Фауна',
  space: 'Космос',
  body: 'Людське тіло',
  food: 'Їжа та напої',
  money: 'Гроші',
  tech: 'Технології',
  people: 'Відомі люди',
  brand: 'Бренди та логотипи',
} as const;
export type WorldTheme = keyof typeof WORLD_THEMES;

/** Тема запитання за його id. */
export const worldThemeOf = (id: string): WorldTheme | null => {
  const code = id.split('-')[0];
  return code in WORLD_THEMES ? (code as WorldTheme) : null;
};

