export type FamilyTheme = keyof typeof FAMILY_THEMES;

/** Тема запитання за його id. */
export const familyThemeOf = (id: string): FamilyTheme | null => {
  const code = id.split('-')[0];
  return code in FAMILY_THEMES ? (code as FamilyTheme) : null;
};

