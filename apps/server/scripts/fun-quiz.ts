/** П'ять тем гри; код теми — префікс id кожного запитання (зручно для статистики за темами). */
export const FUN_THEMES = {
  zoo: 'Тварини й природа',
  food: 'Їжа-дивина',
  toons: 'Мультики й пісні',
  myth: 'Правда чи вигадка',
  riddle: 'Загадки',
} as const;
export type FunTheme = keyof typeof FUN_THEMES;

/** Тема запитання за його id. */
export const funThemeOf = (id: string): FunTheme | null => {
  const code = id.split('-')[0];
  return code in FUN_THEMES ? (code as FunTheme) : null;
};

